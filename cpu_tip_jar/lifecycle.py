"""Operating-system process lifetime guards for the one visible mining session.

Linux: util-linux setpriv sets PR_SET_PDEATHSIG on XMRig via exec.
Windows: a kill-on-close Job Object is held by the GUI process.
No daemon, autostart, privilege escalation, or recurring service.
"""
import os
import shutil
import subprocess


def protected_command(args):
    """Return a process argv that stops the miner when the GUI dies on Linux."""
    if os.name == "nt":
        return args
    if not os.uname().sysname == "Linux":
        raise RuntimeError("Unsupported OS for mining.")
    helper = shutil.which("setpriv")
    if not helper:
        raise RuntimeError(
            "Crash-safe mining on Linux requires 'setpriv' from util-linux. "
            "Install util-linux or use direct donation; mining was not started."
        )
    # setpriv execs XMRig without shell or privilege elevation. SIGKILL is
    # generated by the kernel if the parent process unexpectedly disappears.
    return [helper, "--pdeathsig", "SIGKILL", "--", *args]


if os.name == "nt":
    import ctypes
    from ctypes import wintypes

    class BasicLimitInfo(ctypes.Structure):
        _fields_ = [
            ("PerProcessUserTimeLimit", ctypes.c_longlong),
            ("PerJobUserTimeLimit", ctypes.c_longlong),
            ("LimitFlags", wintypes.DWORD),
            ("MinimumWorkingSetSize", ctypes.c_size_t),
            ("MaximumWorkingSetSize", ctypes.c_size_t),
            ("ActiveProcessLimit", wintypes.DWORD),
            ("Affinity", ctypes.c_size_t),
            ("PriorityClass", wintypes.DWORD),
            ("SchedulingClass", wintypes.DWORD),
        ]

    class IOCounters(ctypes.Structure):
        _fields_ = [
            ("ReadOperationCount", ctypes.c_ulonglong),
            ("WriteOperationCount", ctypes.c_ulonglong),
            ("OtherOperationCount", ctypes.c_ulonglong),
            ("ReadTransferCount", ctypes.c_ulonglong),
            ("WriteTransferCount", ctypes.c_ulonglong),
            ("OtherTransferCount", ctypes.c_ulonglong),
        ]

    class ExtendedLimitInfo(ctypes.Structure):
        _fields_ = [
            ("BasicLimitInformation", BasicLimitInfo),
            ("IoInfo", IOCounters),
            ("ProcessMemoryLimit", ctypes.c_size_t),
            ("JobMemoryLimit", ctypes.c_size_t),
            ("PeakProcessMemoryUsed", ctypes.c_size_t),
            ("PeakJobMemoryUsed", ctypes.c_size_t),
        ]

    _kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    _kernel.CreateJobObjectW.argtypes = [ctypes.c_void_p, wintypes.LPCWSTR]
    _kernel.CreateJobObjectW.restype = ctypes.c_void_p
    _kernel.SetInformationJobObject.argtypes = [
        ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p, wintypes.DWORD]
    _kernel.SetInformationJobObject.restype = wintypes.BOOL
    _kernel.AssignProcessToJobObject.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
    _kernel.AssignProcessToJobObject.restype = wintypes.BOOL
    _kernel.CloseHandle.argtypes = [ctypes.c_void_p]
    _kernel.CloseHandle.restype = wintypes.BOOL


class CrashGuard:
    """Owns a Windows Job Object; on Linux the kernel guards exec'd XMRig."""

    def __init__(self, proc):
        self.handle = None
        if os.name != "nt":
            return
        handle = _kernel.CreateJobObjectW(None, None)
        if not handle:
            raise OSError(ctypes.get_last_error(), "Cannot create Windows process job")
        self.handle = handle
        info = ExtendedLimitInfo()
        info.BasicLimitInformation.LimitFlags = 0x2000  # KILL_ON_JOB_CLOSE
        try:
            ok = _kernel.SetInformationJobObject(
                handle, 9, ctypes.byref(info), ctypes.sizeof(info))
            if not ok:
                raise OSError(ctypes.get_last_error(), "Cannot configure Windows process job")
            ok = _kernel.AssignProcessToJobObject(handle, ctypes.c_void_p(proc._handle))
            if not ok:
                raise OSError(ctypes.get_last_error(), "Cannot attach miner to Windows process job")
        except BaseException:
            self.close()
            raise

    def close(self):
        if self.handle is not None:
            handle, self.handle = self.handle, None
            _kernel.CloseHandle(handle)
